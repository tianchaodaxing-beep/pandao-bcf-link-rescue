/* Node regression tests for the browser's matching and bounded ZIP parser. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
global.fflate = require('../docs/vendor/fflate-0.8.3.js');
vm.runInThisContext(fs.readFileSync(path.join(__dirname, '../docs/rescue.js'), 'utf8'));
const sample = name => fs.readFileSync(path.join(__dirname, '../docs/samples', name));
const old = JSON.parse(sample('old.inventory.json')), updated = JSON.parse(sample('new.inventory.json')), expected = JSON.parse(sample('expected.json'));
const matcher = BCFRescue.matcher(old, updated);
for (const [oldId, newId] of Object.entries(expected.mapping)) assert.equal(matcher.resolve(oldId).new_guid, newId);
const input = BCFRescue.readZip(new Uint8Array(sample('issues.bcfzip')));
assert.equal(Object.keys(input).length, 4);
assert.deepEqual(BCFRescue.readZip(BCFRescue.writeZip(input)), input);
assert.throws(() => BCFRescue.readZip(BCFRescue.writeZip({'../escape': new Uint8Array([1])})), /Unsafe/);
assert.throws(() => BCFRescue.readZip(BCFRescue.writeZip({'bomb': new Uint8Array(1000000)})), /ratio/);
assert.throws(() => BCFRescue.readZip(BCFRescue.writeZip({'dup': new Uint8Array([1]), 'DUP': new Uint8Array([2])})), /Duplicate/);
const original = new Uint8Array(sample('issues.bcfzip'));
const truncated = original.slice(0, original.length - 10);
assert.throws(() => BCFRescue.readZip(truncated), /directory/);
const modified = new Uint8Array(original);
const view = new DataView(modified.buffer);
let central = 0;
while (view.getUint32(central, true) !== 0x02014b50) central++;
view.setUint16(central + 8, view.getUint16(central + 8, true) | 1, true);
assert.throws(() => BCFRescue.readZip(modified), /Encrypted/);
const moved = structuredClone(updated);
moved.frame.contexts[0].translation_m[0] += 10;
assert.equal(BCFRescue.matcher(old, moved).resolve(Object.keys(expected.mapping)[0]).status, 'frame_changed');
console.log('Browser core tests passed: matching, frame shift, roundtrip ZIP, traversal, duplicate, bomb, encryption, truncation.');
